#!/usr/bin/env python3
"""Generate docs/arabic-wording-list.md from the template's message files (build plan package W4).

Run from the repository root:  python3 docs/tools/arabic-wording-list.py
The document is generated, so every message in both files appears, and the counts are computed, not typed.
"""
import json
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
EN = ROOT / "templates/next/messages/en.json"
AR = ROOT / "templates/next/messages/ar.json"
OUT = ROOT / "docs/arabic-wording-list.md"

# Wording changes suggested by review, for the owner to accept or reject. They are not applied to the
# template here: the template is under the L11 licence gate and this package is a document only.
SUGGESTED = [
    ("app.sample_banner", "بيانات تجريبية. كل ما تراه هنا مُختلَق.", "بيانات تجريبية. كل ما تراه هنا وهمي.",
     "\"مُختلَق\" carries the sense of a falsehood (fabricated, made-up as a lie); \"وهمي\" says sample or dummy data without that overtone."),
    ("common.confirm_no", "لا، عُد", "لا، رجوع",
     "\"عُد\" is grammatical but unusual on a button; \"رجوع\" is the usual form for a Back button."),
]


def flat(d, prefix=""):
    out = {}
    for k, v in d.items():
        key = f"{prefix}.{k}" if prefix else k
        if isinstance(v, dict):
            out.update(flat(v, key))
        else:
            out[key] = v
    return out


def main():
    en = flat(json.loads(EN.read_text(encoding="utf-8")))
    ar = flat(json.loads(AR.read_text(encoding="utf-8")))
    missing_ar = [k for k in en if k not in ar]
    missing_en = [k for k in ar if k not in en]
    today = date.today().isoformat()
    L = []
    L += ["# Arabic wording list for the owner to read", ""]
    L += ["| | |", "| --- | --- |",
          "| Written | 11 November 2026, package W4 of `docs/BUILD-PLAN.md` |",
          "| Source | `templates/next/messages/en.json` and `templates/next/messages/ar.json`, the message files of the TypeScript house template |",
          "| How it was made | Generated by `docs/tools/arabic-wording-list.py` from those two files, so every message appears and the counts are computed, not typed. Re-run the script after any change to the files |",
          f"| Count | English messages: {len(en)}. Arabic messages: {len(ar)}. Missing from Arabic: {len(missing_ar)}. Missing from English: {len(missing_en)} |",
          "| Reader | The owner. These are every word a user of a generated app would see in the template today. Please read the Arabic column and mark anything that reads wrongly for a UAE workplace: register, wording, or a term of art |",
          ""]
    L += ["## How to read this", "",
          "Each row is one message. The key is the message's name in the code; the owner can ignore it. Text in curly braces, such as `{name}`, is filled in by the app at run time and must stay as it is in both languages. Arabic is written right to left; the app sets the page direction automatically.",
          "", "| Key | English | Arabic |", "| --- | --- | --- |"]
    for k in en:
        L.append(f"| `{k}` | {en[k]} | {ar.get(k, '**missing**')} |")
    for k in missing_en:
        L.append(f"| `{k}` | **missing** | {ar[k]} |")
    L += ["", "## Suggested changes, for the owner to accept or reject", "",
          "Found by a fresh reviewer on 11 November 2026. Not yet applied: the template's files are under the licence gate L11 of the build plan, and this package is a document only. Once the owner accepts a suggestion and L11 is true, the change is made in `templates/next/messages/ar.json` and this list is regenerated.",
          "", "| Key | Current Arabic | Suggested Arabic | Why |", "| --- | --- | --- | --- |"]
    for key, cur, new, why in SUGGESTED:
        live = ar.get(key, "")
        state = "" if live == cur else " (the file has since changed; re-check)"
        L.append(f"| `{key}` | {cur}{state} | {new} | {why} |")
    L += ["", "## Notes for the owner", "",
          "- The template's role names (Employee, Manager, HR admin) are placeholders from test example 1; each generated app has its own roles, translated at build time.",
          "- The sample-data banner appears on every page of every generated app in Stage 1 and must stay (house standard: sample data is labelled as sample data).",
          "- The app's name, `Internal app` / `تطبيق داخلي`, is a placeholder until a project names its app.",
          "- Messages for later features (confirmation before anything destructive, numbers with their source and period) are already translated so they are ready when those screens appear.",
          "", "## Record", "",
          f"Generated on {today} by `docs/tools/arabic-wording-list.py`. Keys compared one by one: {len(en)} English, {len(ar)} Arabic, {len(missing_ar) + len(missing_en)} missing in either direction."]
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(en)} en, {len(ar)} ar, missing {len(missing_ar)}/{len(missing_en)}")
    return 0 if not (missing_ar or missing_en) else 1


if __name__ == "__main__":
    sys.exit(main())
